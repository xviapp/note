import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

// Build uses the committed CSS, so this repository remains independently buildable.
// Run here alongside packages/theme to check or update the shared family rules.
const source = resolve(
  process.argv.find((arg) => arg.startsWith('--source='))?.slice(9) ||
    fileURLToPath(new URL('../../packages/theme/src/brand-theme.ts', import.meta.url)),
);
const theme = await import(pathToFileURL(source).href);
const light = theme.createBrandPalettes('reader').lightPalette;
const dark = theme.createBrandPalettes('chase').darkPalette;
const values = (palette) => ({
  canvas: palette.canvas,
  surface: palette.surface,
  raised: palette.surfaceRaised,
  soft: palette.surfaceSoft,
  ink: palette.text,
  muted: palette.textMuted,
  line: palette.border,
  'line-strong': palette.controlBorder,
  scrim: palette.overlay,
});
const rules = (selector, values) =>
  `${selector} {\n${Object.entries(values)
    .map(([key, value]) => `  --family-${key}: ${value};`)
    .join('\n')}\n}\n`;
const css =
  '/* Generated by scripts/sync-theme.mjs from packages/theme/src/brand-theme.ts. */\n' +
  rules(':root', {
    ...values(light),
    ...Object.fromEntries(
      Object.entries(theme.spacing).map(([key, value]) => [`space-${key}`, `${value}px`]),
    ),
    ...Object.fromEntries(
      Object.entries(theme.radius).map(([key, value]) => [`radius-${key}`, `${value}px`]),
    ),
    ...Object.fromEntries(
      Object.entries(theme.typography).flatMap(([key, value]) => [
        [`type-${key}`, `${value.fontSize}px`],
        [`leading-${key}`, `${value.lineHeight}px`],
      ]),
    ),
    header: `${theme.appHeaderHeight}px`,
    touch: `${theme.minimumTouchTarget}px`,
    'bottom-item': `${theme.bottomNavigationItemHeight}px`,
    'icon-stroke': theme.iconography.stroke,
    disabled: theme.interaction.disabledOpacity,
    pressed: theme.interaction.pressedOpacity,
  }) +
  '\n' +
  rules(':root[data-theme="dark"]', values(dark));
const target = new URL('../src/family-tokens.css', import.meta.url);
if (process.argv.includes('--write')) writeFileSync(target, css);
else if (readFileSync(target, 'utf8') !== css) {
  console.error('Theme tokens differ. Run npm run theme:sync.');
  process.exitCode = 1;
}
